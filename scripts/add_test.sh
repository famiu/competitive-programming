#!/usr/bin/env bash
# Usage: add_test.sh [dir] [input-file [output-file]]
#
# Creates the next tests/custom_NN.in, reading the input from <input-file> or stdin.
# The expected output comes from <output-file>, else from brute.cpp when it exists, else
# from stdin when it is a terminal. Leaving it empty creates the test without a .out file.
set -euo pipefail
source "$(dirname "$(realpath "${BASH_SOURCE[0]}")")/lib.sh"

parse_problem_args "$@"
dir="$PROBLEM_DIR"
(( ${#PROBLEM_ARGS[@]} <= 2 )) || die "usage: just add-test [dir] [input-file [output-file]]"
in_file="${PROBLEM_ARGS[0]:-}"
out_file="${PROBLEM_ARGS[1]:-}"

tmp="$(mktemp -d)"
trap 'rm -rf -- "$tmp"' EXIT

if [[ -n "$in_file" ]]; then
    [[ -f "$in_file" ]] || die "no such file: $in_file"
    cp "$in_file" "$tmp/in"
else
    [[ -t 0 ]] && printf '%sPaste the input, then press Ctrl-D:%s\n' "$CYAN" "$RESET" >&2
    cat > "$tmp/in"
fi
[[ -s "$tmp/in" ]] || die "the input is empty"

if [[ -n "$out_file" ]]; then
    [[ -f "$out_file" ]] || die "no such file: $out_file"
    cp "$out_file" "$tmp/out"
elif [[ -f "$dir/brute.cpp" ]]; then
    brute_bin="$(bin_path debug "$dir" brute)"
    build debug "$dir/brute.cpp" "$brute_bin" "$dir"
    run_timed "$(time_limit "$dir" debug)" "$tmp/in" "$tmp/out" "$tmp/err" "$brute_bin"
    if ((RUN_STATUS != 0)); then
        [[ -s "$tmp/err" ]] && print_capped "$tmp/err" stderr
        die "brute.cpp failed on the input ($(describe_status "$RUN_STATUS"))"
    fi
    note "expected output generated by brute.cpp"
elif [[ -t 0 ]]; then
    printf '%sPaste the expected output, then press Ctrl-D (leave empty to skip):%s\n' "$CYAN" "$RESET" >&2
    cat > "$tmp/out"
fi

mkdir -p "$dir/tests"
n=1
while [[ -e "$(printf '%s/tests/custom_%02d.in' "$dir" "$n")" ]]; do ((n += 1)); done
base="$(printf '%s/tests/custom_%02d' "$dir" "$n")"
cp "$tmp/in" "$base.in"
printf '%s\n' "$base.in"
if [[ -s "$tmp/out" ]]; then
    cp "$tmp/out" "$base.out"
    printf '%s\n' "$base.out"
fi
