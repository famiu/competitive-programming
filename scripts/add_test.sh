#!/usr/bin/env bash
# Usage: add_test.sh [--sample] [dir] [input-file [output-file]]
#
# Creates the next tests/custom_NN.in, reading the input from <input-file> or stdin and the
# expected output from <output-file> or stdin. When <output-file> is not given and the pasted
# output is empty or stdin is not a terminal, the expected output comes from brute.cpp if it
# exists, else the test is created without a .out file.
#
# With --sample, creates the next sample, tests/NN.in and tests/NN.out, instead. A sample
# needs an expected output and never takes it from brute.cpp.
set -euo pipefail
source "$(dirname "$(realpath "${BASH_SOURCE[0]}")")/lib.sh"

custom=true
prefix=custom_
if [[ "${1:-}" == --sample ]]; then
    custom=false
    prefix=''
    shift
fi
parse_problem_args "$@"
dir="$PROBLEM_DIR"
(( ${#PROBLEM_ARGS[@]} <= 2 )) || die "usage: just add-test [--sample] [dir] [input-file [output-file]]"
in_file="${PROBLEM_ARGS[0]:-}"
out_file="${PROBLEM_ARGS[1]:-}"

tmp="$(mktemp -d)"
trap 'rm -rf -- "$tmp"' EXIT

if [[ -n "$in_file" ]]; then
    [[ -f "$in_file" ]] || die "no such file: $in_file"
    cp "$in_file" "$tmp/in"
else
    [[ -t 0 ]] && printf '%sPaste the input, then press Ctrl-D:%s\n' "$CYAN" "$RESET" >&2
    cat > "$tmp/in"
fi
[[ -s "$tmp/in" ]] || die "the input is empty"

if [[ -n "$out_file" ]]; then
    [[ -f "$out_file" ]] || die "no such file: $out_file"
    cp "$out_file" "$tmp/out"
elif [[ -t 0 ]]; then
    if $custom; then
        prompt="Paste the expected output, then press Ctrl-D (leave empty to"
        if [[ -f "$dir/brute.cpp" ]]; then prompt+=" use brute.cpp):"; else prompt+=" skip):"; fi
    else
        prompt="Paste the expected output, then press Ctrl-D:"
    fi
    printf '%s%s%s\n' "$CYAN" "$prompt" "$RESET" >&2
    cat > "$tmp/out"
fi

if [[ ! -s "$tmp/out" ]]; then
    $custom || die "a sample needs an expected output; pass an output file or paste it"
    if [[ -f "$dir/brute.cpp" ]]; then
        brute_bin="$(bin_path debug "$dir" brute)"
        build debug "$dir/brute.cpp" "$brute_bin" "$dir"
        run_timed "$(time_limit "$dir" debug)" "$tmp/in" "$tmp/out" "$tmp/err" "$brute_bin"
        if ((RUN_STATUS != 0)); then
            [[ -s "$tmp/err" ]] && print_capped "$tmp/err" stderr
            die "brute.cpp failed on the input ($(describe_status "$RUN_STATUS"))"
        fi
        note "expected output generated by brute.cpp"
    fi
fi

mkdir -p "$dir/tests"
n=1
while [[ -e "$(printf '%s/tests/%s%02d.in' "$dir" "$prefix" "$n")" ]]; do ((n += 1)); done
base="$(printf '%s/tests/%s%02d' "$dir" "$prefix" "$n")"
cp "$tmp/in" "$base.in"
printf '%s\n' "$base.in"
if [[ -s "$tmp/out" ]]; then
    cp "$tmp/out" "$base.out"
    printf '%s\n' "$base.out"
fi
